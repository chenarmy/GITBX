import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceCssPath = path.join(repositoryRoot, 'font-packs', 'all-fonts.css');
const coreCssPath = path.join(repositoryRoot, 'src', 'assets', 'fonts.css');
const manifestPath = path.join(repositoryRoot, 'src', 'services', 'optionalFontManifest.generated.ts');
const publicFontRoot = path.join(repositoryRoot, 'public', 'fonts');
const packRoot = path.join(repositoryRoot, 'font-packs');

const OPTIONAL_FAMILIES = new Map([
  ['Alibaba PuHuiTi 3.0', 'alibaba-puhuiti'],
  ['Noto Sans SC', 'noto-sans-sc'],
  ['Noto Serif SC', 'noto-serif-sc'],
  ['Noto Sans JP', 'noto-sans-jp'],
]);

function property(block, name) {
  return new RegExp(`${name}:\\s*([^;]+);`, 'i').exec(block)?.[1]?.trim();
}

function unquote(value = '') {
  return value.replace(/^['"]|['"]$/g, '');
}

function fontFile(block) {
  const source = property(block, 'src') || '';
  const match = /url\((['"]?)(\/fonts\/[^'")]+)\1\)/.exec(source);
  if (!match) throw new Error(`Unable to read font URL from:\n${block}`);
  return match[2].slice('/fonts/'.length).replaceAll('\\', '/');
}

function hashFile(filePath) {
  return crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex');
}

function generate() {
  const fullCss = fs.readFileSync(sourceCssPath, 'utf8');
  const faceBlocks = [...fullCss.matchAll(/@font-face\s*\{[\s\S]*?\n\}/g)].map((match) => match[0]);
  const packs = new Map();
  let coreCss = fullCss.replace(/^\/\*[\s\S]*?\*\/\s*/, '');

  for (const block of faceBlocks) {
    const family = unquote(property(block, 'font-family'));
    const id = OPTIONAL_FAMILIES.get(family);
    const file = fontFile(block);

    if (!id) {
      const localPath = path.join(publicFontRoot, ...file.split('/'));
      if (!fs.existsSync(localPath)) throw new Error(`Bundled font is missing: ${localPath}`);
      continue;
    }

    coreCss = coreCss.replace(block, '');
    const localPath = path.join(packRoot, ...file.split('/'));
    if (!fs.existsSync(localPath)) throw new Error(`Optional font is missing: ${localPath}`);
    const stats = fs.statSync(localPath);
    const face = {
      file,
      style: property(block, 'font-style') || 'normal',
      weight: property(block, 'font-weight') || '400',
      size: stats.size,
      sha256: hashFile(localPath),
    };
    const unicodeRange = property(block, 'unicode-range');
    if (unicodeRange) face.unicodeRange = unicodeRange;

    const pack = packs.get(id) || { id, family, totalBytes: 0, faces: [] };
    pack.totalBytes += stats.size;
    pack.faces.push(face);
    packs.set(id, pack);
  }

  for (const [family, id] of OPTIONAL_FAMILIES) {
    if (!packs.has(id)) throw new Error(`No @font-face rules found for optional family ${family}`);
  }

  const cssHeader = `/*\n * Generated by scripts/generate-font-manifest.mjs.\n * Contains installer-bundled fonts only; optional families live in font-packs/.\n * Do not edit by hand.\n */\n\n`;
  coreCss = cssHeader + coreCss.replace(/\n{3,}/g, '\n\n').trim() + '\n';

  const manifest = `/* Generated by scripts/generate-font-manifest.mjs. Do not edit. */\n\n`
    + `export interface OptionalFontFaceDefinition {\n`
    + `  file: string;\n  style: string;\n  weight: string;\n  size: number;\n  sha256: string;\n  unicodeRange?: string;\n}\n\n`
    + `export interface OptionalFontPackDefinition {\n`
    + `  id: string;\n  family: string;\n  totalBytes: number;\n  faces: OptionalFontFaceDefinition[];\n}\n\n`
    + `export const OPTIONAL_FONT_PACKS: Record<string, OptionalFontPackDefinition> = `
    + `${JSON.stringify(Object.fromEntries(packs), null, 2)};\n`;

  return { coreCss, manifest };
}

function writeOrCheck(filePath, content, check) {
  if (check) {
    const existing = fs.existsSync(filePath)
      ? fs.readFileSync(filePath, 'utf8').replaceAll('\r\n', '\n')
      : null;
    if (existing !== content.replaceAll('\r\n', '\n')) {
      throw new Error(`${path.relative(repositoryRoot, filePath)} is stale; run pnpm fonts:generate`);
    }
    return;
  }
  fs.writeFileSync(filePath, content);
}

const check = process.argv.includes('--check');
const output = generate();
writeOrCheck(coreCssPath, output.coreCss, check);
writeOrCheck(manifestPath, output.manifest, check);
console.log(check ? 'Font bundle outputs are current.' : 'Generated bundled font CSS and optional font manifest.');
